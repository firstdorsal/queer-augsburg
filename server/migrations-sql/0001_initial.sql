-- The whole schema of the v1 server after the move from MongoDB (research-postgres §2).
-- Ids stay the v1 strings and are compared bytewise (COLLATE "C"), like MongoDB compared
-- them, so sort orders and tie-breaks stay the same. Timestamps stay bigint milliseconds:
-- the API, the PWA's delta-sync cursor and the iCal feed use them as they are. Enum labels
-- are the Rust variant names, so SQL, JSON and the TypeScript types share one spelling.
--
-- `seq` (users, meetings, documents) is the order MongoDB kept the documents in: its record
-- ids, which grow with every insert and stay with a document through updates. Queries that
-- MongoDB answered in that order, or that sorted and left ties in it, use `seq` the same way,
-- so rows with equal sort keys come back as before. The migrator fills it in dump order
-- (mongodump writes the natural order) and moves the identity past it; new rows take the
-- next value.

-- users ------------------------------------------------------------------------------------

CREATE TYPE user_capability AS ENUM (
    'UpdateMeetings', 'GetUsers', 'UpdateMemberStatus', 'CreateMember', 'SendMassEmail',
    'UpdateDocuments'
);

-- The seam with the auth half (research-auth §3.3): it adds its columns and tables with
-- `user_id text REFERENCES users(_id)`. `_id` is the interossea id or generate_id(30).
CREATE TABLE users (
    _id          text COLLATE "C" PRIMARY KEY,
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    -- A stored null is read as the empty list (research-postgres §3.6 item 1).
    capabilities user_capability[] NOT NULL DEFAULT '{}',
    -- Fields of old documents the server never read (`admin`, `imported_from`); kept by
    -- the migrator, never read.
    extra        jsonb
);

CREATE TYPE member_type AS ENUM ('Active', 'Supporting');
CREATE TYPE membership_status AS ENUM ('Approved', 'Rejected', 'Pending', 'Left', 'Expelled');

-- `User.member`: one row per user that submitted a membership.
CREATE TABLE members (
    user_id          text COLLATE "C" PRIMARY KEY REFERENCES users(_id) ON DELETE CASCADE,
    member_type      member_type NOT NULL,
    natural_person   boolean NOT NULL,
    name_passport    text,
    name_first       text,
    name_last        text,
    CHECK (num_nonnulls(name_passport, name_first, name_last) IN (0, 3)),
    institution      text,
    pronouns         text,
    address_street   text NOT NULL,
    address_number   text NOT NULL,
    address_addition text,
    address_zip      text NOT NULL,
    address_city     text NOT NULL,
    address_country  text NOT NULL,
    -- The contact email the member edits, not the login email.
    email            text NOT NULL,
    phone            text,
    start_time_ms    bigint NOT NULL,
    end_time_ms      bigint,
    -- `Option<MembershipStatus>`: null is a stored value.
    status           membership_status,
    user_notes       text,
    admin_notes      text,
    reference        text,
    approved_charter boolean NOT NULL,
    approved_privacy boolean NOT NULL,
    above_18         boolean NOT NULL,
    honorary         boolean NOT NULL
);
CREATE INDEX members_status ON members (status);
CREATE INDEX members_start_time ON members (start_time_ms DESC);

-- `originalUsers`: the user as stored right after the first membership submission.
-- Written once, never read by the server.
-- No reference to users: the archive outlives accounts, two snapshots already have none.
CREATE TABLE original_users (
    user_id    text COLLATE "C" NOT NULL,
    snapshot   jsonb NOT NULL,
    created_at bigint NOT NULL,
    PRIMARY KEY (user_id, created_at)
);

-- places and meetings ----------------------------------------------------------------------

CREATE TABLE places (
    _id        text COLLATE "C" PRIMARY KEY,
    name       text NOT NULL,
    -- place_rules::place_name_key, computed in Rust; one place per name.
    name_key   text COLLATE "C" NOT NULL UNIQUE,
    lat        double precision NOT NULL,
    lon        double precision NOT NULL,
    -- Both null for places from before `created` existed.
    created_by text,
    created_at bigint,
    CHECK ((created_by IS NULL) = (created_at IS NULL))
);

CREATE TYPE meeting_status AS ENUM ('Planned', 'Active');
CREATE TYPE common_meeting_tag AS ENUM (
    'Kultur', 'Party', 'Orga', 'Sport', 'Education', 'Meet', 'Students', 'Marketing',
    'Cinema', 'Talks', 'Open', 'Explores', 'Connect', 'Ostqueer', 'Queermas'
);
CREATE TYPE queer_meeting_tag AS ENUM (
    'Everyone', 'Queer', 'Gay', 'Lesbian', 'Trans', 'Bi', 'Asexual', 'Aromantic', 'Inter',
    'Poly', 'Pan'
);

CREATE TABLE meetings (
    _id                   text COLLATE "C" PRIMARY KEY,
    seq                   bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    title                 text NOT NULL,
    authority             text NOT NULL,
    age_restriction       smallint[] NOT NULL DEFAULT '{}',
    -- Null for some imported meetings (types.rs `Meeting::time`).
    time                  bigint,
    -- `Meeting.location`, the display copy of the place; all or none.
    location_name         text,
    location_lat          double precision,
    location_lon          double precision,
    CHECK (num_nonnulls(location_name, location_lat, location_lon) IN (0, 3)),
    -- No foreign key: v1 never had one, `location` is the copy readers use, and the
    -- migrator reports ids without a place instead of refusing the meeting.
    place_id              text COLLATE "C",
    -- `Meeting.online`; `online_url` holds members-only links, which never leave the
    -- server in lists. `url_hidden` is a response-only flag and is not stored.
    online_platform       text,
    online_url            text,
    online_members_only   boolean,
    CHECK ((online_platform IS NULL) = (online_members_only IS NULL)),
    CHECK (online_url IS NULL OR online_platform IS NOT NULL),
    place_to_be_announced boolean NOT NULL DEFAULT false,
    description           text NOT NULL,
    -- f32 as sent, so the JSON output stays identical.
    price                 real[] NOT NULL DEFAULT '{}',
    trigger_warning       text,
    -- u16
    attendance            integer,
    rating                real,
    accessibility         text,
    tags_freeform         text[] NOT NULL DEFAULT '{}',
    tags_common           common_meeting_tag[] NOT NULL DEFAULT '{}',
    tags_queer            queer_meeting_tag[] NOT NULL DEFAULT '{}',
    status                meeting_status NOT NULL,
    -- `Option<bool>`: null exists in old documents.
    cancelled             boolean,
    deleted_at            bigint
);
-- The date ranges of the public overview.
CREATE INDEX meetings_time ON meetings (time);
-- Every list request filters by status and excludes deleted meetings; equal times come
-- newest first, as MongoDB returned them (a backward scan of its `time` index).
CREATE INDEX meetings_list ON meetings (status, time DESC, seq DESC) WHERE deleted_at IS NULL;
CREATE INDEX meetings_deleted_at ON meetings (deleted_at) WHERE deleted_at IS NOT NULL;
CREATE INDEX meetings_place ON meetings (place_id);

-- `Meeting.changed`: the position keeps the order, `at` is what delta sync filters by.
CREATE TABLE meeting_changes (
    meeting_id text COLLATE "C" NOT NULL REFERENCES meetings(_id) ON DELETE CASCADE,
    position   integer NOT NULL,
    at         bigint NOT NULL,
    by         text NOT NULL,
    PRIMARY KEY (meeting_id, position)
);
CREATE INDEX meeting_changes_at ON meeting_changes (at);

-- email ------------------------------------------------------------------------------------

CREATE TYPE draft_status AS ENUM ('Pending', 'Processing');

-- A mass mail waiting for its confirmation code; read whole once and deleted.
CREATE TABLE email_drafts (
    _id               text COLLATE "C" PRIMARY KEY,
    sender_id         text NOT NULL,
    sender_email      text NOT NULL,
    subject           text NOT NULL,
    body              text NOT NULL,
    -- Vec<EmailAttachment>, with the base64 data.
    attachments       jsonb NOT NULL DEFAULT '[]',
    verification_code text NOT NULL,
    created_at        bigint NOT NULL,
    recipient_count   integer NOT NULL,
    status            draft_status NOT NULL DEFAULT 'Pending',
    reply_to          text
);

CREATE TABLE sent_email_logs (
    _id              text COLLATE "C" PRIMARY KEY,
    sender_id        text NOT NULL,
    sender_email     text NOT NULL,
    subject          text NOT NULL,
    body             text NOT NULL,
    attachment_names text[] NOT NULL DEFAULT '{}',
    sent_at          bigint NOT NULL,
    successful_count integer NOT NULL,
    failed_count     integer NOT NULL,
    failed_emails    text[] NOT NULL DEFAULT '{}',
    reply_to         text
);

-- documents --------------------------------------------------------------------------------

CREATE TABLE documents (
    _id           text COLLATE "C" PRIMARY KEY,
    seq           bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    title         text NOT NULL,
    content       text NOT NULL,
    -- The Yjs state, the source of truth for the text (document_rooms.rs). Large values are
    -- stored out of line, so reads of the other columns do not touch it.
    state         bytea NOT NULL,
    state_version bigint NOT NULL,
    created_by    text NOT NULL,
    created_at    bigint NOT NULL,
    updated_at    bigint NOT NULL,
    deleted_by    text,
    deleted_at    bigint,
    CHECK ((deleted_by IS NULL) = (deleted_at IS NULL)),
    -- document_rooms::MAX_STATE_BYTES
    CHECK (octet_length(state) <= 6000000)
);
-- The search reads the live documents in MongoDB's natural order (`seq`).
CREATE INDEX documents_live ON documents (seq) WHERE deleted_at IS NULL;

CREATE TABLE document_groups (
    _id            text COLLATE "C" PRIMARY KEY,
    name           text NOT NULL,
    -- document_rules::sort_key, computed in Rust; one group per name.
    name_key       text COLLATE "C" NOT NULL UNIQUE,
    -- A wish list (document_rules::apply_order): ids that are gone are skipped.
    document_order text[] NOT NULL DEFAULT '{}'
);

-- `StoredDocument.group_ids`, in the order they were sent. An id sent twice is kept twice,
-- as MongoDB stored the array as it came.
CREATE TABLE document_group_members (
    document_id text COLLATE "C" NOT NULL REFERENCES documents(_id) ON DELETE CASCADE,
    group_id    text COLLATE "C" NOT NULL REFERENCES document_groups(_id) ON DELETE CASCADE,
    position    integer NOT NULL,
    PRIMARY KEY (document_id, position)
);
CREATE INDEX document_group_members_group ON document_group_members (group_id);

-- The one record "main": the wanted order of the groups.
CREATE TABLE document_group_order (
    _id       text PRIMARY KEY CHECK (_id = 'main'),
    group_ids text[] NOT NULL
);

CREATE TABLE document_versions (
    _id         text COLLATE "C" PRIMARY KEY,
    -- Documents are only ever soft-deleted, so the cascade does not fire today.
    document_id text COLLATE "C" NOT NULL REFERENCES documents(_id) ON DELETE CASCADE,
    content     text NOT NULL,
    editors     text[] NOT NULL DEFAULT '{}',
    saved_at    bigint NOT NULL
);
CREATE INDEX document_versions_newest ON document_versions (document_id, saved_at DESC, _id DESC);
